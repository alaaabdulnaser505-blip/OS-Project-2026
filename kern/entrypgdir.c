uint32 entry_pgtable[NPTENTRIES];

// The entry.S page directory maps the first 4MB of physical memory
// starting at virtual address KERNBASE (that is, it maps virtual
// addresses [KERNBASE, KERNBASE+4MB) to physical addresses [0, 4MB)).
// We choose 4MB because that's how much we can map with one page
// table and it's enough to get us through early boot.  We also map
// virtual addresses [0, 4MB) to physical addresses [0, 4MB); this
// region is critical for a few instructions in entry.S and then we
// never use it again.
//
// Page directories (and page tables), must start on a page boundary,
// hence the "__aligned__" attribute.  Also, because of restrictions
// related to linking and static initializers, we use "x + PERM_PRESENT"
// here, rather than the more standard "x | PERM_PRESENT".  Everywhere else
// you should use "|" to combine flags.
__attribute__((__aligned__(PAGE_SIZE)))
uint32 entry_pgdir[NPDENTRIES] = {
	// Map VA's [0, 4MB) to PA's [0, 4MB)
	[0]
		= ((uint32)entry_pgtable - KERNEL_BASE) + PERM_PRESENT ,
	// Map VA's [KERNBASE, KERNBASE+4MB) to PA's [0, 4MB)
	[KERNEL_BASE>>PDXSHIFT]
		= ((uint32)entry_pgtable - KERNEL_BASE) + PERM_PRESENT + PERM_WRITEABLE
};

